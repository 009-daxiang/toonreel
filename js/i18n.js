let currentLang = 'en';

function t(key, vars) {
  let s = (I18N[currentLang] && I18N[currentLang][key]) ?? I18N.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

function trGenre(g) {
  return (GENRE_I18N[currentLang] && GENRE_I18N[currentLang][g]) || g;
}

function trGenres(show) {
  return show.genres.map(trGenre).join(' · ');
}

function detectLang() {
  const saved = store.get('lang', null);
  if (saved && I18N[saved]) return saved;
  const nav = (navigator.language || 'en').toLowerCase();
  if (nav.startsWith('zh')) {
    return /-tw|-hk|-mo|hant/i.test(nav) ? 'zht' : 'zh';
  }
  if (nav.startsWith('id')) return 'id';
  if (nav.startsWith('th')) return 'th';
  if (nav.startsWith('vi')) return 'vi';
  if (nav.startsWith('ms') || nav.startsWith('my')) return 'ms';
  if (nav.startsWith('fil') || nav.startsWith('tl')) return 'fil';
  return 'en';
}

/* Replace text of all [data-i18n] / [data-i18n-ph] nodes */
function applyI18n() {
  document.documentElement.lang = currentLang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  document.title = currentLang === 'en'
    ? 'YT688 — AI Micro Dramas, Binge in Minutes'
    : `YT688 — ${t('nav_home')} · AI Micro Dramas`;
}

function initLang(onChange) {
  currentLang = detectLang();
  const btn = document.getElementById('langBtn');
  const menu = document.getElementById('langMenu');
  if (btn && menu) {
    const renderMenu = () => {
      menu.innerHTML = `<div class="lang-head">${t('lang_title')}</div>` + LANGS.map(l => `
        <button class="lang-opt ${l.code === currentLang ? 'on' : ''}" data-lang="${l.code}">
          <span>${l.label}</span>${l.code === currentLang ? '<span class="check">✓</span>' : ''}
        </button>`).join('');
      menu.querySelectorAll('.lang-opt').forEach(o =>
        o.addEventListener('click', () => {
          currentLang = o.dataset.lang;
          store.set('lang', currentLang);
          renderMenu();
          updateLangBtn();
          applyI18n();
          onChange?.();
          menu.classList.remove('open');
        })
      );
    };
    const updateLangBtn = () => {
      document.getElementById('langCode').textContent = currentLang.toUpperCase();
    };
    btn.addEventListener('click', (e) => {
      e.stopPropagation();
      renderMenu();
      menu.classList.toggle('open');
    });
    document.addEventListener('click', (e) => {
      if (!e.target.closest('.lang-wrap')) menu.classList.remove('open');
    });
    updateLangBtn();
  }
  applyI18n();
}
